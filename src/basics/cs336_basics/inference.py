def setup_inference_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser()

    parser.add_argument("--run_id", help="id of wandb run", type=str)
    parser.add_argument("--wandb_path", help="path to wandb run", type=str)
    parser.add_argument("--temperature", help="temperature of softmax", type=float, default=1.0)
    parser.add_argument("--p", help="cutoff probability for top word choices", type=float)
    parser.add_argument("--vocab_file", help="tokenizer vocab file", type=str)
    parser.add_argument("--merge_file", help="tokenizer merge file", type=str)
    parser.add_argument("--max_tokens", help="max number of tokens generated by model", type=int)
    return parser

@torch.no_grad()
def decode(prompt: str, model: TransformerLM, device: torch.device,
           max_tokens: int, temperature: float,  p: float, tokenizer: Tokenizer):
    tokenized_prompt = tokenizer.encode(prompt)
    tokenized_prompt = torch.tensor(tokenized_prompt, dtype=torch.long, device=device)
    model.to(device)
    predicted_idx = []
    end_of_text_id = tokenizer.rev_vocab_map['<|endoftext|>'.encode('utf-8')]
    for _ in range(max_tokens):
        logits = model.forward(tokenized_prompt)
        prob = softmax(logits / temperature, i=-1)
        prob = prob.select(dim=-2, index=-1)
        prob_sorted, idx = torch.sort(prob, descending=True, dim=-1)
        cum_prob = torch.cumsum(prob_sorted, dim=-1)
        if cum_prob[0] > p:
            prob_sorted[1:] = 0.0
        else:
            prob_sorted[(cum_prob > p)] = 0.0
        trunc_cum_prob = torch.cumsum(prob_sorted, dim=-1)
        normalized_prob = prob_sorted / trunc_cum_prob
        sample_idx = torch.multinomial(normalized_prob, num_samples=1)
        next_word_idx = idx.gather(dim=-1, index=sample_idx)
        tokenized_prompt = torch.concat([tokenized_prompt[1:], next_word_idx])
        predicted_idx.append(next_word_idx.detach().cpu().item())
        if next_word_idx.item() == end_of_text_id:
            break

    return tokenizer.decode(predicted_idx)

if __name__ == "__main__":
    inf_parser = setup_inference_parser()
    inf_args = inf_parser.parse_args()

    wandb_folder = inf_args.wandb_path
    folders = os.listdir(wandb_folder)

    log_folder = [f for f in folders if f.endswith(inf_args.run_id)][0]
    config_file  = os.path.join(wandb_folder, log_folder, 'files', 'config.yaml')

    with open(config_file, 'r') as f:
        cfg = yaml.safe_load(f)

    model_hyper_params = cfg['model']['value']
    optimizer_hyper_params = cfg['optimizer']['value']
    # lr might be read in as str
    optimizer_hyper_params['lr'] = eval(optimizer_hyper_params['lr'])
    device = cfg['device']['value']

    lm = TransformerLM(**model_hyper_params)
    optimizer = AdamW(lm.parameters(), **optimizer_hyper_params)

    checkpoint_folder = cfg['checkpoint']['value']
    checkpoint_file = cfg['checkpoint_file']['value']

    load_checkpoint(os.path.join(checkpoint_folder, checkpoint_file), lm, optimizer)
    tokenizer = Tokenizer.from_files(inf_args.vocab_file, inf_args.merge_file, ['<|endoftext|>'])
    while True:
        user_input = input("Enter prompt\n")
        if user_input.lower() == 'exit':
            break
        answer = decode(user_input, lm, device, inf_args.max_tokens, inf_args.temperature, inf_args.p, tokenizer)
        print("Model Answer: ", answer)

